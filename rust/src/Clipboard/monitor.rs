//! Port of `Clipboard/ClipboardMonitor.swift`.
//!
//! Polls NSPasteboard.general.changeCount (macOS has no change notification).
//! Reading one integer twice a second is the standard approach and costs
//! nothing measurable.
//!
//! Swift's state lives on the main actor; here the state is a plain Mutex —
//! the timer fires on the main run loop and the workspace/lock notifications
//! arrive on arbitrary threads, so the mutex (not the actor) is the isolation.
//! ObjC objects the state holds (timer, observer tokens) are stored as raw
//! retained pointers: they are alive for the process lifetime and only ever
//! touched under the lock.

use std::path::PathBuf;
use std::sync::{Mutex, OnceLock};

use objc2::rc::Retained;
use objc2::runtime::{AnyClass, AnyObject};
use objc2::{class, msg_send};
use objc2_app_kit::{NSBitmapImageRep, NSPasteboard, NSWorkspace};
use objc2_foundation::{
    ns_string, NSArray, NSDictionary, NSDistributedNotificationCenter, NSData, NSNotification,
    NSString, NSTimer,
};

use crate::app::preferences::Preferences;
use crate::capture::pasteboard_writer;
use crate::capture::screenshotter;
